package app.tessera.personal

import java.io.File
import java.io.FileOutputStream
import java.io.OutputStream

/** Byte staging only. CSV generation and database snapshots stay in TypeScript. */
internal class StagedCsv(directory: File) {
    private val file: File
    private var stream: FileOutputStream?
    init {
        check(directory.isDirectory || directory.mkdirs())
        file = File.createTempFile(".tessera-csv-", ".tmp", directory)
        try { stream = FileOutputStream(file) }
        catch (error: Exception) { file.delete(); throw error }
    }
    fun write(text: String) {
        require(text.length <= 32000)
        (stream ?: error("fileError")).write(text.toByteArray(Charsets.UTF_8))
    }
    fun finish(openDestination: () -> OutputStream) {
        val output = stream ?: error("fileError")
        output.fd.sync()
        output.close()
        stream = null
        // The provider is first opened only after all generated bytes are ready.
        file.inputStream().use { input ->
            openDestination().use { destination -> input.copyTo(destination); destination.flush() }
        }
        file.delete()
    }
    fun abort() {
        try { stream?.close() } finally { stream = null; file.delete() }
    }
    companion object {
        fun removeInterrupted(directory: File) {
            directory.listFiles()?.filter { it.name.startsWith(".tessera-csv-") && it.name.endsWith(".tmp") }
                ?.forEach { it.delete() }
        }
    }
}
