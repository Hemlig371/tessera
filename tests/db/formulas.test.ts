import { afterEach, describe, expect, it, vi } from 'vitest';
import { adapters, fixture } from '../support/fixture';
import { canonical, type Entry, type JsonValue } from '../../src/core/model';
import { exportDatabaseArchive, importDatabaseArchive } from '../../src/core/database-archive';
import { Repository } from '../../src/core/repository';

describe.each(adapters)('%s calculated values and dependency cache', kind => {
  const opened: Awaited<ReturnType<typeof fixture>>[] = [];
  afterEach(async () => { vi.useRealTimers(); for (const f of opened.splice(0)) await f.cleanup(); });
  async function setup() {
    const f = await fixture(kind); opened.push(f); const api = f.api!, library = await api.createLibrary('Формулы');
    const collection = await api.createCollection(library.id, 'Числа', 'Название');
    return { f, api, library, collection };
  }
  const computed = (entry: Entry | null, id: string) => entry!.computed?.[id];
  it('keeps exact intermediates across calculated dependencies and never writes results into source/history/log', async () => {
    const { f, api, collection } = await setup();
    const amount = await api.createField(collection.id, 'Сумма', 'decimal');
    const third = await api.createField(collection.id, 'Треть', 'formula', { formula: `[${amount.id}]/3` });
    const whole = await api.createField(collection.id, 'Обратно', 'formula', { formula: `[${third.id}]*3`, indexed: true });
    const entry = await api.saveEntry(collection.id, { [collection.primary_field_id]: 'Точная цепочка', [amount.id]: '1' });
    const source = () => f.db.read(async s => ({ records: await s.query('SELECT id,data,hlc,updated_at FROM records'), versions: await s.query('SELECT * FROM record_versions'), log: await s.query('SELECT * FROM change_log'), clock: await s.query("SELECT value FROM local_settings WHERE key='hlc'") }));
    const before = await source(), loaded = await api.getEntry(entry.id);
    expect(computed(loaded, third.id)).toMatchObject({ value: '0.33333', error: null });
    expect(computed(loaded, whole.id)).toMatchObject({ value: '1', error: null });
    expect(loaded!.data).not.toHaveProperty(whole.id);
    expect(JSON.parse(canonical(loaded as unknown as JsonValue))).not.toHaveProperty('computed');
    expect(await source()).toEqual(before);
    expect((await api.queryEntries({ collection_id: collection.id, filters: [{ field_id: whole.id, op: 'eq', value: '1' }] })).items.map(row => row.id)).toEqual([entry.id]);
    await expect(api.saveEntry(collection.id, { [whole.id]: '8' }, entry.id, entry.hlc)).rejects.toThrow('readOnlyField');
    const preview = await api.previewFormulas(collection.id, { ...entry.data, [amount.id]: '6' }, entry.id);
    expect((preview as NonNullable<Entry['computed']>)[whole.id]!.value).toBe('6');
    expect(await source()).toEqual(before);
    const renamed = await api.updateField(amount.id, { name: 'Переименованная сумма' });
    expect(renamed.id).toBe(amount.id);
    expect((await api.listFields(collection.id)).find(field => field.id === third.id)!.config).toContain(amount.id);
    expect(computed(await api.getEntry(entry.id), whole.id)!.value).toBe('1');
  });
  it('invalidates direct/reverse aggregates for source edits, reparenting, delete/restore and missing fields', async () => {
    const { api, library } = await setup();
    const products = await api.createCollection(library.id, 'Товары', 'Название'), orders = await api.createCollection(library.id, 'Заказы', 'Название'), lines = await api.createCollection(library.id, 'Позиции', 'Название');
    const price = await api.createField(products.id, 'Цена', 'money', { currency: '₽' });
    const product = await api.saveEntry(products.id, { [products.primary_field_id]: 'Товар', [price.id]: '5.55' });
    const order = await api.saveEntry(orders.id, { [orders.primary_field_id]: 'Первый' }), other = await api.saveEntry(orders.id, { [orders.primary_field_id]: 'Второй' });
    const productRef = await api.createField(lines.id, 'Товар', 'relation', { target_collection_id: products.id });
    const orderRef = await api.createField(lines.id, 'Заказ', 'relation', { target_collection_id: orders.id });
    const quantity = await api.createField(lines.id, 'Количество', 'decimal');
    const subtotal = await api.createField(lines.id, 'Стоимость', 'formula', { formula: `[${quantity.id}]*[${productRef.id}].[${price.id}]` });
    const reverse = await api.createField(orders.id, 'Позиции', 'backlink', { source_field_id: orderRef.id });
    const total = await api.createField(orders.id, 'Итого', 'aggregate', { formula: `SUM([${reverse.id}].[${subtotal.id}])` });
    const average = await api.createField(orders.id, 'Среднее', 'aggregate', { formula: `AVERAGE([${reverse.id}].[${subtotal.id}])` });
    const line = await api.saveEntry(lines.id, { [lines.primary_field_id]: 'Две', [productRef.id]: product.id, [orderRef.id]: order.id, [quantity.id]: '2' });
    await api.saveEntry(lines.id, { [lines.primary_field_id]: 'Ноль', [productRef.id]: product.id, [orderRef.id]: order.id, [quantity.id]: '0' });
    await api.saveEntry(lines.id, { [lines.primary_field_id]: 'NULL', [productRef.id]: product.id, [orderRef.id]: order.id });
    expect(computed(await api.getEntry(order.id), total.id)!.value).toBe('11.1');
    expect(computed(await api.getEntry(order.id), average.id)!.value).toBe('5.55');
    await api.saveEntry(products.id, { [price.id]: '7.25' }, product.id, product.hlc);
    expect(computed(await api.getEntry(order.id), total.id)!.value).toBe('14.5');
    expect((await api.getEntry(order.id))!.hlc).toBe(order.hlc);
    expect((await api.getHistory(order.id)).versions).toHaveLength(1);
    await api.saveEntry(lines.id, { [orderRef.id]: other.id }, line.id, line.hlc);
    expect(computed(await api.getEntry(order.id), total.id)!.value).toBe('0');
    expect(computed(await api.getEntry(other.id), total.id)!.value).toBe('14.5');
    const current = (await api.getEntry(product.id))!; await api.setDeleted('record', current.id, true, current.hlc);
    expect(computed(await api.getEntry(other.id), total.id)!.error).toBe('formulaReference');
    await api.setDeleted('record', current.id, false);
    expect(computed(await api.getEntry(other.id), total.id)!.value).toBe('14.5');
    await api.setDeleted('field', price.id, true);
    expect(computed(await api.getEntry(other.id), total.id)!.error).toBe('formulaReference');
    await expect(api.createField(products.id, 'Другое', 'text')).resolves.toHaveProperty('type', 'text');
  });
  it('builds static filter/sort/group keys for all rows before SQL pagination and refreshes invalidated keys', async () => {
    const { api, collection } = await setup();
    const number = await api.createField(collection.id, 'Число', 'decimal');
    const doubled = await api.createField(collection.id, 'Удвоено', 'formula', { formula: `[${number.id}]*2`, indexed: true });
    await api.importEntries(collection.id, Array.from({ length: 211 }, (_, index) => ({ [collection.primary_field_id]: 'Строка ' + index, [number.id]: String(index) })));
    const top = await api.queryEntries({ collection_id: collection.id, sort_field: doubled.id, direction: 'desc', limit: 3 });
    expect(top.items.map(row => row.computed![doubled.id]!.value)).toEqual(['420', '418', '416']);
    expect((await api.queryEntries({ collection_id: collection.id, group_field: doubled.id, sort_field: doubled.id, filters: [{ field_id: doubled.id, op: 'gt', value: '400' }] })).items).toHaveLength(10);
    const entry = (await api.queryEntries({ collection_id: collection.id, sort_field: doubled.id, limit: 1 })).items[0]!;
    await api.saveEntry(collection.id, { [number.id]: '1000' }, entry.id, entry.hlc);
    expect((await api.queryEntries({ collection_id: collection.id, sort_field: doubled.id, direction: 'desc', limit: 1 })).items[0]!.computed![doubled.id]!.value).toBe('2000');
  });
  it('rejects dependency cycles atomically and exposes type/division/reference errors', async () => {
    const { api, collection } = await setup();
    const a = await api.createField(collection.id, 'А', 'formula', { formula: '1' }), b = await api.createField(collection.id, 'Б', 'formula', { formula: `[${a.id}]+1` });
    await expect(api.updateField(a.id, { config: { formula: `[${b.id}]+1` } })).rejects.toThrow('formulaCycle');
    const bad = await api.createField(collection.id, 'Ошибка', 'formula', { formula: '1/0' });
    const entry = await api.saveEntry(collection.id, { [collection.primary_field_id]: 'Ошибки' });
    expect(computed(await api.getEntry(entry.id), a.id)!.value).toBe('1');
    expect(computed(await api.getEntry(entry.id), bad.id)).toMatchObject({ value: null, error: 'divisionByZero' });
    const secret = await api.createField(collection.id, 'Секрет', 'secret');
    await expect(api.createField(collection.id, 'Утечка', 'formula', { formula: `[${secret.id}]`, result_type: 'text' })).rejects.toThrow('formulaReference');
  });
  it('refreshes NOW and transitive dependents on display while explicitly refusing dynamic indexes', async () => {
    const { api, collection } = await setup();
    const now = await api.createField(collection.id, 'Сейчас', 'formula', { formula: 'NOW()', result_type: 'local_datetime' });
    const dependent = await api.createField(collection.id, 'Подпись', 'formula', { formula: `CONCAT([${now.id}],"!")`, result_type: 'text' });
    const entry = await api.saveEntry(collection.id, { [collection.primary_field_id]: 'Динамика' });
    vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date(2026, 10, 17, 12, 30));
    expect(computed(await api.getEntry(entry.id), dependent.id)!.value).toBe('2026-11-17T12:30:00.000!');
    vi.setSystemTime(new Date(2026, 10, 18, 9, 15));
    expect((await api.queryEntries({ collection_id: collection.id })).items[0]!.computed![dependent.id]!.value).toBe('2026-11-18T09:15:00.000!');
    await expect(api.queryEntries({ collection_id: collection.id, sort_field: now.id })).rejects.toThrow('dynamicFormulaIndex');
    await expect(api.queryEntries({ collection_id: collection.id, filters: [{ field_id: dependent.id, op: 'eq', value: 'x' }] })).rejects.toThrow('dynamicFormulaIndex');
    await expect(api.updateField(now.id, { config: { formula: 'NOW()', result_type: 'local_datetime', indexed: true } })).rejects.toThrow('dynamicFormulaIndex');
    await expect(api.updateDisplayProfile(collection.default_profile_id!, { definition: { fields: [], list: { sort_field: now.id } } })).rejects.toThrow('dynamicFormulaIndex');
    expect((await api.getEntry(entry.id))!.hlc).toBe(entry.hlc);
  });
  it('exports definitions and source values while rebuilding local results after archive import', async () => {
    const { f, api, collection } = await setup();
    const number = await api.createField(collection.id, 'Число', 'decimal'), doubled = await api.createField(collection.id, 'Расчёт', 'formula', { formula: `[${number.id}]*2` });
    const entry = await api.saveEntry(collection.id, { [collection.primary_field_id]: 'Архив', [number.id]: '1.23456' });
    expect(computed(await api.getEntry(entry.id), doubled.id)!.value).toBe('2.46912');
    const chunks: Uint8Array[] = [];
    await exportDatabaseArchive(f.db, f.files, { write: async bytes => { chunks.push(bytes); }, finish: async () => {}, abort: async () => { throw new Error('unexpected abort'); } });
    const bytes = new Uint8Array(Buffer.concat(chunks));
    expect(new TextDecoder().decode(bytes)).not.toContain('"_formula"');
    const target = await fixture(kind, false); opened.push(target);
    await importDatabaseArchive({ name: 'formulas.zip', mime: 'application/zip', size: bytes.length, read: async (offset, count) => bytes.slice(offset, offset + count) }, target.db, target.files);
    const restored = await Repository.open(target.db, target.files);
    expect(restored.deviceId).not.toBe(api.deviceId);
    expect(computed(await restored.getEntry(entry.id), doubled.id)!.value).toBe('2.46912');
    expect((await restored.getHistory(entry.id)).versions[0]!.snapshot.data).not.toHaveProperty(doubled.id);
  });
});
