import { expect, test } from '../support/e2e-test';
test('a damaged creation draft is preserved and a fresh record can be created explicitly', async ({ page }) => {
  test.setTimeout(60000);
  await page.goto('/'); await expect(page.locator('[data-catalog=libraries]')).toBeVisible();
  const request = async (data: object) => {
    const result = await page.request.post('/__test-sqlite', { data }); expect(result.ok(), await result.text()).toBe(true);
    return (await result.json()).value;
  };
  const scope = await request({ op: 'draft-recovery-seed' });
  const path = `drafts/${scope.dataset_id}/${scope.library_id}/${scope.collection_id}.json`, damaged = [255, 123, 0, 17, 125];
  await request({ op: 'local-write', path, bytes: damaged });
  const snapshot = () => request({ op: 'query', sql: "SELECT (SELECT count(*) FROM records) AS records,(SELECT count(*) FROM record_versions) AS versions,(SELECT count(*) FROM change_log) AS changes,(SELECT value FROM local_settings WHERE key='hlc') AS hlc" });
  const before = await snapshot();
  await page.reload();
  await page.getByRole('button', { name: `Открыть библиотеку «${scope.library_name}»`, exact: true }).click();
  await page.getByRole('button', { name: 'Открыть коллекцию «Записи»', exact: true }).click();
  await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  await expect(page.locator('[data-draft-recovery]')).toContainText('сохранён отдельно');
  const recovered = await page.locator('[data-draft-recovery]').getAttribute('data-draft-recovery');
  expect(await request({ op: 'local-read', path: recovered })).toEqual(damaged);
  expect(await snapshot()).toEqual(before);
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('Новая после повреждения');
  await page.getByRole('button', { name: 'Назад', exact: true }).click();
  expect(await snapshot()).toEqual(before);
  const live = await request({ op: 'local-read', path });
  expect(JSON.parse(new TextDecoder().decode(new Uint8Array(live))).data[scope.primary_field_id]).toBe('Новая после повреждения');
  await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Название', exact: true })).toHaveValue('Новая после повреждения');
  await expect(page.locator('[data-draft-recovery]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.locator('[data-editor]')).toHaveCount(0);
  await expect(page.locator('.entry')).toContainText('Новая после повреждения');
  const after = await snapshot(); expect(after[0].records).toBe(before[0].records + 1); expect(after[0].versions).toBe(before[0].versions + 1);
  expect(await request({ op: 'local-read', path })).toBeNull();
  expect(await request({ op: 'local-read', path: recovered })).toEqual(damaged);
  await page.reload(); await expect(page.locator('[data-catalog=libraries]')).toBeVisible();
  await expect(page.locator('[data-editor]')).toHaveCount(0);
  expect(await request({ op: 'local-read', path: recovered })).toEqual(damaged);
});
