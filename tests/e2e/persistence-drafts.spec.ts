import { openQuickCreation, showList } from '../support/ui-actions';
import { test, expect } from '@playwright/test';
import type { Entry } from '../../src/core/model';
test('Notes creation drafts survive close/restart; existing edits and stale-form rejection leave the draft unchanged', async ({ page }) => {
  test.setTimeout(90000);
  await page.goto('/'); await expect(page.locator('aside')).toBeVisible();
  const request = async (data: object) => (await (await page.request.post('/__test-sqlite', { data })).json()).value as unknown;
  const scope = await request({ op: 'draft-seed' }) as { dataset_id: string; library_id: string; collection_id: string; primary_field_id: string; body_field_id: string };
  const path = `drafts/${scope.dataset_id}/${scope.library_id}/${scope.collection_id}.json`;
  const bytes = () => request({ op: 'local-read', path });
  const read = async () => { const data = await bytes() as number[] | null; return data ? JSON.parse(new TextDecoder().decode(new Uint8Array(data))) as { action: { create_id: string }; data: Record<string,string> } : null; };
  const navigate = async () => {
    await page.getByRole('button', { name: 'Заметки (dev/CI)', exact: true }).click();
    await page.getByRole('button', { name: 'Заметки', exact: true }).click();
    await expect(page.getByRole('button', { name: '+ Новая запись', exact: true })).toBeEnabled();
  };
  const closeCreation = () => page.locator('form').getByRole('button', { name: 'Закрыть', exact: true }).click();
  await page.reload(); await navigate();
  const before = await request({ op: 'query', sql: 'SELECT * FROM change_log ORDER BY seq' });
  await showList(page); await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('Новая заметка 🦔');
  await page.getByRole('textbox', { name: 'Текст', exact: true }).fill('Не терять длинный текст');
  await expect.poll(async () => (await read())?.data[scope.primary_field_id], { timeout: 8000 }).toBe('Новая заметка 🦔');
  expect(await request({ op: 'query', sql: 'SELECT * FROM records WHERE collection_id=?', params: [scope.collection_id] })).toEqual([]);
  expect(await request({ op: 'query', sql: 'SELECT * FROM change_log ORDER BY seq' })).toEqual(before);
  await closeCreation(); await expect(page.locator('[data-editor]')).toHaveCount(0);
  const originalFile = await bytes(); expect(originalFile).not.toBeNull();
  await page.reload(); await expect(page.locator('[data-editor]')).toHaveCount(0); await navigate();
  await expect(page.locator('[data-editor]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Темы', exact: true }).click();
  await expect(page.locator('[data-editor]')).toHaveCount(0);
  await showList(page); await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Название', exact: true })).toHaveValue('');
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('Черновик другой коллекции');
  await closeCreation(); expect(await bytes()).toEqual(originalFile);
  const existing = await request({ op: 'draft-existing', params: [scope.collection_id] }) as Entry;
  await page.reload(); await navigate(); await showList(page); await page.locator('.entry').click();
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click();
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('Не сохранять редактирование');
  await page.getByRole('button', { name: 'Отмена', exact: true }).click(); expect(await bytes()).toEqual(originalFile);
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click();
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('Моя редакция');
  const fresh = await request({ op: 'stale-update', params: [existing.id, 'Свежая внешняя редакция'] }) as Entry;
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Сохранить мою редакцию' })).toBeVisible();
  const rejected = await request({ op: 'query', sql: 'SELECT hlc FROM records WHERE id=?', params: [existing.id] });
  expect(rejected).toEqual([{ hlc: fresh.hlc }]); expect(await bytes()).toEqual(originalFile);
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('Моя подтверждённая редакция');
  await page.getByRole('button', { name: 'Сохранить мою редакцию' }).click();
  await expect(page.locator('[data-editor]')).toHaveCount(0); expect(await bytes()).toEqual(originalFile);
  await openQuickCreation(page);
  await expect(page.getByRole('textbox', { name: 'Название', exact: true })).toHaveValue('Новая заметка 🦔');
  await expect(page.getByRole('textbox', { name: 'Текст', exact: true })).toHaveValue('Не терять длинный текст');
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('После системного возврата');
  await page.evaluate(() => window.dispatchEvent(new Event('tessera-back')));
  await expect(page.locator('[data-editor]')).toHaveCount(0);
  expect((await read())?.data[scope.primary_field_id]).toBe('После системного возврата');
  await showList(page); await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  await page.getByRole('textbox', { name: 'Название', exact: true }).fill('При сворачивании');
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect.poll(async () => (await read())?.data[scope.primary_field_id]).toBe('При сворачивании');
  await page.reload(); await navigate(); await expect(page.locator('[data-editor]')).toHaveCount(0);
  await showList(page); await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  const reserved = (await read())!.action.create_id;
  await expect(page.getByRole('textbox', { name: 'Название', exact: true })).toHaveValue('При сворачивании');
  await request({ op: 'execute', sql: "CREATE TRIGGER fail_draft_save BEFORE INSERT ON record_versions BEGIN SELECT RAISE(ABORT,'draft save failure'); END" });
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click(); await expect(page.getByRole('alert')).toBeVisible();
  expect(await read()).not.toBeNull();
  expect(await request({ op: 'query', sql: 'SELECT * FROM records WHERE id=?', params: [reserved] })).toEqual([]);
  await request({ op: 'execute', sql: 'DROP TRIGGER fail_draft_save' });
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click(); await expect(page.locator('[data-editor]')).toHaveCount(0);
  await expect.poll(read).toBeNull();
  expect(await request({ op: 'query', sql: 'SELECT id FROM records WHERE id=?', params: [reserved] })).toEqual([{ id: reserved }]);
  expect(await request({ op: 'query', sql: 'SELECT id FROM record_versions WHERE record_id=?', params: [reserved] })).toHaveLength(1);
});
