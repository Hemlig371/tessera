import { test, expect } from '@playwright/test';
import { openConstructor, showList } from '../support/ui-actions';

test('visual rows preserve cells while resizing/reordering; forms adapt and reveal collapsed required inputs', async ({ page }) => {
  test.setTimeout(90000);
  await page.goto('/'); await expect(page.locator('aside')).toBeVisible();
  await page.locator('.topbar').getByRole('button', { name: 'Оформление', exact: true }).click();
  await page.getByRole('combobox', { name: 'Размер текста', exact: true }).selectOption('1.5');
  await page.getByRole('button', { name: 'Сохранить оформление', exact: true }).click();
  const seeded = await page.request.post('/__test-sqlite', { data: { op: 'layout-seed' } });
  expect(seeded.ok(), await seeded.text()).toBe(true);
  const scope = (await seeded.json()).value as { collection_id: string; primary: string; count: string; flag: string; body: string; date: string };
  const query = async (sql: string, params: string[] = []) => (await (await page.request.post('/__test-sqlite', { data: { op: 'query', sql, params } })).json()).value as unknown;
  const before = await query('SELECT * FROM records WHERE collection_id=?', [scope.collection_id]);
  const versions = await query('SELECT v.* FROM record_versions v JOIN records r ON r.id=v.record_id WHERE r.collection_id=?', [scope.collection_id]);
  await page.reload();
  await page.getByRole('button', { name: 'Заметки: строки (dev/CI)', exact: true }).click();
  await page.getByRole('button', { name: 'Заметки', exact: true }).click();
  await page.locator('.entry').filter({ hasText: 'Компоновка исходная' }).click();
  await page.locator('.detail').getByRole('button', { name: 'Редактировать', exact: true }).click();
  await page.setViewportSize({ width: 844, height: 390 });
  await page.getByRole('button', { name: 'Сохранить', exact: true }).focus();
  await page.keyboard.press('Shift+Tab'); await page.keyboard.press('Shift+Tab'); await page.keyboard.press('Shift+Tab');
  const markdownPreview = page.getByRole('button', { name: 'Предпросмотр Markdown', exact: true });
  await expect(markdownPreview).toBeFocused();
  await expect.poll(() => markdownPreview.evaluate(element => {
    const control = element.getBoundingClientRect(), heading = document.querySelector('.editor-heading')!.getBoundingClientRect();
    return control.top >= heading.bottom && control.bottom <= innerHeight;
  })).toBe(true);
  await page.getByRole('button', { name: 'Отмена', exact: true }).click();
  await expect(page.locator('[data-editor]')).toHaveCount(0); await page.getByRole('button', { name: 'К списку', exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await openConstructor(page); await page.getByRole('button', { name: 'Форма', exact: true }).click();
  const rows = page.locator('.row-designer'), first = rows.first();
  await expect(rows).toHaveCount(3);
  await first.getByRole('combobox', { name: 'Колонок', exact: true }).selectOption('1');
  await expect(rows).toHaveCount(5);
  await first.getByRole('combobox', { name: 'Колонок', exact: true }).selectOption('3');
  await first.getByRole('combobox', { name: 'Поле 2', exact: true }).selectOption(scope.count);
  await first.getByRole('combobox', { name: 'Поле 3', exact: true }).selectOption(scope.flag);
  await first.getByRole('textbox', { name: 'Группа полей', exact: true }).fill('Основное');
  await page.getByRole('button', { name: 'Добавить строку', exact: true }).click();
  await rows.last().getByRole('combobox', { name: 'Поле 1', exact: true }).selectOption(scope.body);
  await rows.last().getByRole('textbox', { name: 'Группа полей', exact: true }).fill('Текст');
  await page.getByRole('group', { name: 'Текст', exact: true }).getByRole('checkbox', { name: 'Свернуть поле по умолчанию' }).check();
  await page.getByRole('button', { name: 'Сохранить настройку', exact: true }).click();
  await expect(page.locator('[data-editor]')).toHaveCount(0);
  expect(await query('SELECT * FROM records WHERE collection_id=?', [scope.collection_id])).toEqual(before);
  expect(await query('SELECT v.* FROM record_versions v JOIN records r ON r.id=v.record_id WHERE r.collection_id=?', [scope.collection_id])).toEqual(versions);
  const configs = await query("SELECT config FROM ui_configs WHERE collection_id=? AND kind='form'", [scope.collection_id]) as { config: string }[];
  expect(JSON.parse(configs[0]!.config).rows.flatMap((row: { field_ids: string[] }) => row.field_ids)).toEqual([scope.primary, scope.count, scope.flag, scope.date, scope.body]);
  await page.getByRole('button', { name: 'Готово, к данным' }).click();
  await showList(page); await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  const dialog = page.locator('[data-editor]'), title = dialog.getByRole('textbox', { name: 'Название', exact: true });
  await expect(title).not.toBeVisible();
  await expect.poll(() => dialog.locator('.layout-row').first().evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(3);
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(title).toBeVisible();
  await title.fill('Колонки сохранены');
  await expect(dialog.getByRole('spinbutton', { name: 'Приоритет', exact: true })).toHaveValue('0');
  await expect(dialog.getByRole('combobox', { name: 'Избранное', exact: true })).toHaveValue('false');
  await dialog.locator('summary').filter({ hasText: /^Текст$/ }).click();
  await dialog.getByRole('textbox', { name: 'Текст', exact: true }).fill('**Тело**\nбез потери 🦔');
  await page.setViewportSize({ width: 1060, height: 900 });
  await expect.poll(() => dialog.locator('.layout-row').first().evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(1);
  await expect(title).toHaveValue('Колонки сохранены');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => dialog.locator('.layout-row').first().evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)).toBe(1);
  await expect(title).toHaveValue('Колонки сохранены');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dialog.locator('form').getByRole('button', { name: 'Закрыть', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(await query('SELECT * FROM records WHERE collection_id=?', [scope.collection_id])).toEqual(before);
  await showList(page); await page.getByRole('button', { name: '+ Новая запись', exact: true }).click();
  await dialog.locator('summary').filter({ hasText: /^Текст$/ }).click();
  await expect(dialog.getByRole('textbox', { name: 'Текст', exact: true })).toHaveValue('**Тело**\nбез потери 🦔');
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await showList(page); await page.locator('.entry').filter({ hasText: 'Колонки сохранены' }).click();
  await expect(page.locator('.detail .layout-row').first()).toContainText('Тело');
  await expect(page.locator('.detail .layout-row').first().locator('.markdown strong')).toBeVisible();
  await expect(page.locator('.detail .layout-row').first()).not.toContainText('Приоритет');
  expect(await query('SELECT * FROM records WHERE id=?', [(before as { id: string }[])[0]!.id])).toEqual(before);
});
